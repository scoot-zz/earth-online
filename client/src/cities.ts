function slug(en: string): string {
  return en
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

export const CITIES: City[] = ROWS.map(
  ([zh, en, country, region, lat, lng, tz, tier, flags]) => {
    const id = slug(en);
    return {
      id,
      zh,
      en,
      country,
      region,
      lat,
      lng,
      tz,
      tier,
      labelTier: (tier === 1 && L1_PLATE_DEMOTED.has(id) ? 2 : tier) as CityTier,
      capital: flags?.c === 1,
      wiki: flags?.w ?? en,
    };
  },
);

export const CITY_BY_ID = new Map(CITIES.map((c) => [c.id, c]));
