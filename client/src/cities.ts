// Global mid/large city library for the weather globe (~345 cities).
// Fields: zh name, English name, country (zh), province/state (zh),
// lat, lng, IANA timezone, tier (1 = megacity/major capital shown from the
// farthest zoom, 2 = large city, 3 = mid-size city), optional flags
// ({ c: capital, w: Wikipedia article title when it differs from `en` }).
// Coordinates are city-center approximations used for globe placement and
// the Open-Meteo query point.
//
// `labelTier` drives the NAME PLATE — the city's only marker since the
// white-dot layer was removed — and is deliberately stricter at the
// far (L1) zoom: only a curated whitelist of megacities / major
// capitals earns a plate from orbit. Dense-cluster tier-1 cities
// (Tianjin next to Beijing, Nanjing / Suzhou / Hangzhou next to
// Shanghai, Shenzhen / Hong Kong next to Guangzhou, Qingdao /
// Zhengzhou / Changsha / Shenyang / Harbin, Taipei) have their plate
// demoted to labelTier 2 — it appears (and becomes tappable) only
// once the user zooms into the L2 band. China therefore shows just 7
// name plates at L1: Beijing, Shanghai, Guangzhou, Chongqing, Chengdu,
// Wuhan, Xi'an. `tier` itself now only orders focus-flight depth
// fallbacks; visibility and picking both follow `labelTier`.

export type CityTier = 1 | 2 | 3;

export interface City {
  id: string;
  zh: string;
  en: string;
  country: string;
  region: string;
  lat: number;
  lng: number;
  tz: string;
  tier: CityTier;
  labelTier: CityTier;
  capital: boolean;
  wiki: string;
}

